package com.example.demo.modules.product.application.mapper;

import com.example.demo.common.mapper.BaseMapper;
import com.example.demo.modules.product.application.dto.request.CreateCategoryRequest;
import com.example.demo.modules.product.application.dto.request.UpdateCategoryRequest;
import com.example.demo.modules.product.application.dto.response.CategoryResponse;
import com.example.demo.modules.product.domain.model.Category;
import org.mapstruct.*;
import org.springframework.stereotype.Component;

import java.util.*;
import java.util.stream.Collectors;

/**
 * Lean MapStruct mapper for Category entity <-> DTOs
 * 
 * Performance optimized - avoids deep object graphs and N+1 queries
 *
 * @author PIM Team
 * @version 1.0
 */
@Mapper(
    componentModel = "spring",
    unmappedTargetPolicy = ReportingPolicy.IGNORE,
    nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE,
    nullValueCheckStrategy = NullValueCheckStrategy.ALWAYS,
    injectionStrategy = InjectionStrategy.CONSTRUCTOR
)
@Component
public abstract class CategoryMapper implements BaseMapper<Category, CategoryResponse> {

    // ====================================
    // Entity to Response - LEAN VERSION
    // ====================================

    /**
     * Map Category entity to CategoryResponse (LEAN - no children)
     * 
     * Default mapping - optimized for list views and performance.
     * Children should be loaded separately when needed.
     */
    @Override
    @Mapping(target = "parentId", source = "parent.id")
    @Mapping(target = "path", expression = "java(buildCategoryPath(category))")
    @Mapping(target = "childrenCount", expression = "java(getChildrenCount(category))")
    public abstract CategoryResponse toDto(Category category);

    /**
     * Alias for better readability
     */
    public CategoryResponse toResponse(Category category) {
        if (category == null) {
            return null;
        }
        return toDto(category);
    }

    /**
     * Map list of categories to responses (OPTIMIZED)
     */
    @Override
    public List<CategoryResponse> toDtoList(List<Category> categories) {
        if (categories == null || categories.isEmpty()) {
            return Collections.emptyList();
        }
        return categories.stream()
            .map(this::toResponse)
            .collect(Collectors.toList());
    }

    /**
     * Map with pre-calculated paths (for batch operations)
     * 
     * Use when you have pre-calculated paths to avoid redundant calculations
     */
    public CategoryResponse toResponseWithPath(Category category, String precalculatedPath) {
        if (category == null) {
            return null;
        }
        CategoryResponse response = toDto(category);
        response.setPath(precalculatedPath);
        return response;
    }

    /**
     * Map with product count (injected from service layer)
     */
    public CategoryResponse toResponseWithProductCount(Category category, Long productCount) {
        if (category == null) {
            return null;
        }
        CategoryResponse response = toDto(category);
        response.setProductCount(productCount);
        return response;
    }

    // ====================================
    // Request to Entity - CREATE
    // ====================================

    /**
     * Map CreateCategoryRequest to new Category entity
     */
    @Mapping(target = "parent", ignore = true) // Set by service layer
    @Mapping(target = "children", ignore = true)
    @Mapping(target = "level", ignore = true) // Calculated by service
    @Mapping(target = "path", ignore = true) // Calculated by service
    @Mapping(target = "urlSlug", ignore = true) // Generated by service
    public abstract Category fromCreateRequest(CreateCategoryRequest request);

    /**
     * Not supported for Response -> Entity conversion
     */
    @Override
    public Category toEntity(CategoryResponse dto) {
        throw new UnsupportedOperationException(
            "Cannot create entity from response DTO. Use fromCreateRequest() instead."
        );
    }

    // ====================================
    // Request to Entity - UPDATE
    // ====================================

    /**
     * Update existing Category from UpdateCategoryRequest
     * 
     * Only updates mutable fields, preserves audit and system fields
     */
    @BeanMapping(
        nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE,
        nullValueCheckStrategy = NullValueCheckStrategy.ALWAYS
    )
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "code", ignore = true) // Immutable
    @Mapping(target = "parent", ignore = true) // Set by service layer
    @Mapping(target = "children", ignore = true)
    @Mapping(target = "level", ignore = true) // Recalculated by service
    @Mapping(target = "path", ignore = true) // Recalculated by service
    @Mapping(target = "urlSlug", ignore = true) // Regenerated by service if name changes
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedAt", ignore = true) // Set by BaseEntity
    @Mapping(target = "updatedBy", ignore = true) // Set by AuditingEntityListener
    @Mapping(target = "version", ignore = true) // Managed by JPA
    @Mapping(target = "deleted", ignore = true)
    @Mapping(target = "deletedAt", ignore = true)
    @Mapping(target = "deletedBy", ignore = true)
    public abstract void updateEntityFromRequest(
        UpdateCategoryRequest request, 
        @MappingTarget Category entity
    );

    /**
     * Deprecated - use updateEntityFromRequest
     */
    @Deprecated
    public Category updateEntityFromDto(UpdateCategoryRequest dto, Category entity) {
        updateEntityFromRequest(dto, entity);
        return entity;
    }

    // ====================================
    // Helper Methods - OPTIMIZED
    // ====================================

    /**
     * Build category path (breadcrumb)
     * 
     * Walks up the parent chain to build full path.
     * Consider caching this value in the entity for better performance.
     */
    protected String buildCategoryPath(Category category) {
        if (category == null) {
            return null;
        }

        // Use StringBuilder for better performance with many levels
        List<String> pathSegments = new ArrayList<>();
        Category current = category;
        int maxDepth = 10; // Prevent infinite loops
        int depth = 0;

        while (current != null && depth < maxDepth) {
            pathSegments.add(0, current.getName());
            current = current.getParent();
            depth++;
        }

        return pathSegments.isEmpty() ? null : String.join(" > ", pathSegments);
    }

    /**
     * Get children count (avoid loading full collection)
     */
    protected Integer getChildrenCount(Category category) {
        if (category == null || category.getChildren() == null) {
            return 0;
        }
        return category.getChildren().size();
    }

    // ====================================
    // Batch Operations - PERFORMANCE
    // ====================================

    /**
     * Map categories with pre-calculated product counts
     * 
     * Use when you have counts from a batch query to avoid N+1
     * 
     * @param categories List of categories
     * @param productCounts Map of categoryId -> product count
     */
    public List<CategoryResponse> toResponseListWithProductCounts(
            List<Category> categories,
            Map<UUID, Long> productCounts
    ) {
        if (categories == null || categories.isEmpty()) {
            return Collections.emptyList();
        }

        return categories.stream()
            .map(category -> {
                CategoryResponse response = toDto(category);
                if (productCounts != null && productCounts.containsKey(category.getId())) {
                    response.setProductCount(productCounts.get(category.getId()));
                }
                return response;
            })
            .collect(Collectors.toList());
    }

    /**
     * Map categories with pre-calculated paths and counts
     * 
     * Ultimate performance optimization for large batch operations
     */
    public List<CategoryResponse> toResponseListOptimized(
            List<Category> categories,
            Map<UUID, String> paths,
            Map<UUID, Long> productCounts
    ) {
        if (categories == null || categories.isEmpty()) {
            return Collections.emptyList();
        }

        return categories.stream()
            .map(category -> {
                CategoryResponse response = toDto(category);
                
                // Set pre-calculated path
                if (paths != null && paths.containsKey(category.getId())) {
                    response.setPath(paths.get(category.getId()));
                }
                
                // Set pre-calculated product count
                if (productCounts != null && productCounts.containsKey(category.getId())) {
                    response.setProductCount(productCounts.get(category.getId()));
                }
                
                return response;
            })
            .collect(Collectors.toList());
    }

    // ====================================
    // Utility Methods
    // ====================================

    /**
     * Create minimal summary from Category
     * 
     * Use for dropdowns, selects, and references
     */
    public CategorySummary toSummary(Category category) {
        if (category == null) {
            return null;
        }
        
        return CategorySummary.builder()
            .id(category.getId())
            .code(category.getCode())
            .name(category.getName())
            .slug(category.getUrlSlug())
            .level(category.getLevel())
            .build();
    }

    /**
     * Map list to summaries
     */
    public List<CategorySummary> toSummaryList(List<Category> categories) {
        if (categories == null || categories.isEmpty()) {
            return Collections.emptyList();
        }
        return categories.stream()
            .map(this::toSummary)
            .collect(Collectors.toList());
    }

    // ====================================
    // Nested DTO
    // ====================================

    /**
     * Lightweight category summary
     */
    @lombok.Data
    @lombok.Builder
    @lombok.NoArgsConstructor
    @lombok.AllArgsConstructor
    public static class CategorySummary {
        private UUID id;
        private String code;
        private String name;
        private String slug;
        private Integer level;
    }
}