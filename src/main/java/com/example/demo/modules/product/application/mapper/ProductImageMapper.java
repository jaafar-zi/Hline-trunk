package com.example.demo.modules.product.application.mapper;

import com.example.demo.common.mapper.BaseMapper;
import com.example.demo.modules.product.application.dto.request.AddProductImageRequest;
import com.example.demo.modules.product.application.dto.request.UpdateProductImageRequest;
import com.example.demo.modules.product.application.dto.response.ProductImageResponse;
import com.example.demo.modules.product.domain.model.ProductImage;
import com.example.demo.modules.product.domain.model.vo.ImageType;
import org.mapstruct.*;
import org.springframework.stereotype.Component;

import java.util.*;
import java.util.stream.Collectors;

/**
 * Lean MapStruct mapper for ProductImage entity <-> DTOs
 * 
 * Performance optimized - avoids heavy computed fields in responses
 *
 * @author PIM Team
 * @version 1.0
 */
@Mapper(
    componentModel = "spring",
    unmappedTargetPolicy = ReportingPolicy.IGNORE,
    nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE,
    nullValueCheckStrategy = NullValueCheckStrategy.ALWAYS,
    injectionStrategy = InjectionStrategy.CONSTRUCTOR,
    imports = {ImageType.class}
)
@Component
public abstract class ProductImageMapper implements BaseMapper<ProductImage, ProductImageResponse> {

    // ====================================
    // Entity to Response - LEAN
    // ====================================

    /**
     * Map ProductImage entity to ProductImageResponse (LEAN)
     */
    @Override
    @Mapping(target = "productId", source = "product.id")
    @Mapping(target = "variantId", ignore = true) // Not in entity yet
    @Mapping(target = "imageType", source = "imageType")
    @Mapping(target = "url", source = "url")
    @Mapping(target = "thumbnailUrl", source = "thumbnailUrl")
    @Mapping(target = "altText", source = "altText")
    @Mapping(target = "title", source = "title")
    @Mapping(target = "displayOrder", source = "displayOrder")
    @Mapping(target = "mimeType", source = "mimeType")
    @Mapping(target = "fileSize", source = "fileSize")
    @Mapping(target = "width", source = "width")
    @Mapping(target = "height", source = "height")
    public abstract ProductImageResponse toDto(ProductImage productImage);

    /**
     * Alias for better readability
     */
    public ProductImageResponse toResponse(ProductImage productImage) {
        return productImage != null ? toDto(productImage) : null;
    }

    /**
     * Map list to responses
     */
    @Override
    public List<ProductImageResponse> toDtoList(List<ProductImage> images) {
        if (images == null || images.isEmpty()) {
            return Collections.emptyList();
        }
        return images.stream()
            .map(this::toResponse)
            .collect(Collectors.toList());
    }

    /**
     * Map to sorted gallery list
     */
    public List<ProductImageResponse> toSortedList(List<ProductImage> images) {
        if (images == null || images.isEmpty()) {
            return Collections.emptyList();
        }

        return images.stream()
            .map(this::toResponse)
            .sorted(Comparator.comparing(ProductImageResponse::getDisplayOrder)
                .thenComparing(img -> img.getId() != null ? img.getId() : UUID.randomUUID()))
            .collect(Collectors.toList());
    }

    // ====================================
    // Request to Entity - CREATE
    // ====================================

    /**
     * Map AddProductImageRequest to ProductImage entity
     */
    @Mapping(target = "product", ignore = true) // Set by service
    @Mapping(target = "fileName", source = "fileName")
    @Mapping(target = "originalFileName", source = "fileName") // Use fileName as originalFileName
    @Mapping(target = "url", source = "url")
    @Mapping(target = "imageType", expression = "java(mapImageType(request.getImageType()))")
    @Mapping(target = "altText", source = "altText")
    @Mapping(target = "title", source = "title")
    @Mapping(target = "displayOrder", source = "displayOrder")
    @Mapping(target = "mimeType", source = "mimeType")
    @Mapping(target = "fileSize", source = "fileSize")
    @Mapping(target = "width", source = "width")
    @Mapping(target = "height", source = "height")
    // Fields set by service
    @Mapping(target = "thumbnailUrl", ignore = true) // Generated by image service
    @Mapping(target = "caption", ignore = true)
    @Mapping(target = "storagePath", source = "filePath") // Map filePath to storagePath
    @Mapping(target = "storageProvider", ignore = true) // Set by storage service
    @Mapping(target = "cdnUrl", ignore = true) // Set by CDN service
    public abstract ProductImage fromAddRequest(AddProductImageRequest request);

    /**
     * Not supported
     */
    @Override
    public ProductImage toEntity(ProductImageResponse dto) {
        throw new UnsupportedOperationException(
            "Cannot create entity from response DTO. Use fromAddRequest() instead."
        );
    }

    // ====================================
    // Request to Entity - UPDATE
    // ====================================

    /**
     * Update existing ProductImage from UpdateProductImageRequest
     */
    @BeanMapping(
        nullValuePropertyMappingStrategy = NullValuePropertyMappingStrategy.IGNORE,
        nullValueCheckStrategy = NullValueCheckStrategy.ALWAYS
    )
    @Mapping(target = "product", ignore = true)
    @Mapping(target = "imageType", expression = "java(mapImageType(request.getImageType()))")
    @Mapping(target = "altText", source = "altText")
    @Mapping(target = "title", source = "title")
    @Mapping(target = "caption", source = "caption")
    @Mapping(target = "displayOrder", source = "displayOrder")
    // Immutable fields
    @Mapping(target = "fileName", ignore = true)
    @Mapping(target = "originalFileName", ignore = true)
    @Mapping(target = "url", ignore = true) // Changed via separate service method
    @Mapping(target = "thumbnailUrl", ignore = true)
    @Mapping(target = "storagePath", ignore = true)
    @Mapping(target = "storageProvider", ignore = true)
    @Mapping(target = "cdnUrl", ignore = true)
    @Mapping(target = "mimeType", ignore = true)
    @Mapping(target = "fileSize", ignore = true)
    @Mapping(target = "width", ignore = true)
    @Mapping(target = "height", ignore = true)
    public abstract void updateEntityFromRequest(
        UpdateProductImageRequest request,
        @MappingTarget ProductImage entity
    );

    // ====================================
    // Helper Methods
    // ====================================

    /**
     * Map string imageType to ImageType enum
     */
    protected ImageType mapImageType(String imageTypeStr) {
        if (imageTypeStr == null || imageTypeStr.isBlank()) {
            return ImageType.GALLERY; // Default
        }
        
        try {
            return ImageType.valueOf(imageTypeStr.toUpperCase());
        } catch (IllegalArgumentException e) {
            return ImageType.GALLERY; // Fallback to default
        }
    }

    // ====================================
    // Specialized Mappings
    // ====================================

    /**
     * Map only URLs for simple image gallery
     */
    public List<String> toUrlList(List<ProductImage> images) {
        if (images == null || images.isEmpty()) {
            return Collections.emptyList();
        }

        return images.stream()
            .map(ProductImage::getUrl)
            .filter(Objects::nonNull)
            .collect(Collectors.toList());
    }

    /**
     * Map images by type
     */
    public List<ProductImageResponse> filterByType(List<ProductImage> images, ImageType imageType) {
        if (images == null || images.isEmpty() || imageType == null) {
            return Collections.emptyList();
        }

        return images.stream()
            .filter(img -> imageType.equals(img.getImageType()))
            .map(this::toResponse)
            .sorted(Comparator.comparing(ProductImageResponse::getDisplayOrder))
            .collect(Collectors.toList());
    }

    /**
     * Get primary image only
     */
    public ProductImageResponse toPrimaryImageResponse(List<ProductImage> images) {
        if (images == null || images.isEmpty()) {
            return null;
        }

        return images.stream()
            .filter(img -> ImageType.PRIMARY.equals(img.getImageType()))
            .findFirst()
            .map(this::toResponse)
            .orElse(null);
    }

    /**
     * Get gallery images (non-primary)
     */
    public List<ProductImageResponse> toGalleryImages(List<ProductImage> images) {
        if (images == null || images.isEmpty()) {
            return Collections.emptyList();
        }

        return images.stream()
            .filter(img -> !ImageType.PRIMARY.equals(img.getImageType()))
            .map(this::toResponse)
            .sorted(Comparator.comparing(ProductImageResponse::getDisplayOrder))
            .collect(Collectors.toList());
    }

    // ====================================
    // Utility Methods
    // ====================================

    /**
     * Create minimal image summary
     */
    public ImageSummary toSummary(ProductImage image) {
        if (image == null) {
            return null;
        }

        return ImageSummary.builder()
            .id(image.getId())
            .url(image.getUrl())
            .thumbnailUrl(image.getThumbnailUrl())
            .altText(image.getAltText())
            .imageType(image.getImageType() != null ? image.getImageType().name() : null)
            .displayOrder(image.getDisplayOrder())
            .build();
    }

    /**
     * Map to summary list
     */
    public List<ImageSummary> toSummaryList(List<ProductImage> images) {
        if (images == null || images.isEmpty()) {
            return Collections.emptyList();
        }

        return images.stream()
            .map(this::toSummary)
            .sorted(Comparator.comparing(ImageSummary::getDisplayOrder))
            .collect(Collectors.toList());
    }

    /**
     * Batch create from requests
     */
    public List<ProductImage> fromAddRequestList(List<AddProductImageRequest> requests) {
        if (requests == null || requests.isEmpty()) {
            return Collections.emptyList();
        }
        
        return requests.stream()
            .map(this::fromAddRequest)
            .collect(Collectors.toList());
    }

    // ====================================
    // Nested DTO
    // ====================================

    /**
     * Lightweight image summary for simple displays
     */
    @lombok.Data
    @lombok.Builder
    @lombok.NoArgsConstructor
    @lombok.AllArgsConstructor
    public static class ImageSummary {
        private UUID id;
        private String url;
        private String thumbnailUrl;
        private String altText;
        private String imageType;
        private Integer displayOrder;

        public String getDisplayUrl() {
            return thumbnailUrl != null ? thumbnailUrl : url;
        }
    }
}